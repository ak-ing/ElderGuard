/** Material 3 没有的语义色 */
@Immutable
data class ExtendedColors(
  val warning: Color,
  val onWarning: Color,
  val warningContainer: Color,
  val onWarningContainer: Color,
)

private val LightExtended = ExtendedColors(WarningLight, OnWarningLight, WarningContainerLight, OnWarningContainerLight)
private val DarkExtended = ExtendedColors(WarningDark, OnWarningDark, WarningContainerDark, OnWarningContainerDark)

private val LocalExtendedColors = staticCompositionLocalOf { LightExtended }

object AppTheme {
  val extendedColors: ExtendedColors
    @Composable get() = LocalExtendedColors.current
}

@Composable
fun Theme(darkTheme: Boolean = isSystemInDarkTheme(), content: @Composable () -> Unit) {
  CompositionLocalProvider(LocalExtendedColors provides if (darkTheme) DarkExtended else LightExtended) {
    MaterialTheme(
      colorScheme = if (darkTheme) DarkScheme else LightScheme,
      typography = Typography,
      shapes = AppShapes,
      content = content,
    )
  }
}
